test('a member without Manage Server cannot reach the dashboard or the API', async ({ browser }) => {
  const page = await loginAs(browser, IDS.member);
  await expect(page.getByText('No servers with BotCooks yet')).toBeVisible();
  await page.goto(`/dashboard/${GUILD}`);
  await expect(page).toHaveURL(/denied=/);
  const res = await page.evaluate(async (g) => (await fetch(`/api/guilds/${g}/settings`)).status, GUILD);
  expect(res).toBe(403);
  await page.context().close();
});

test('delegation: helpers get only the delegated section and cannot escalate', async ({ browser }) => {
  const owner = await loginAs(browser, IDS.owner);
  await owner.goto(`/dashboard/${GUILD}/admin`);
  await owner.getByLabel('Role to add').selectOption({ label: '@Helpers' });
  await owner.getByRole('button', { name: 'Add', exact: true }).click();
  await owner.getByRole('group', { name: '@Helpers' }).getByLabel('Welcome & goodbye').check();
  await owner.getByRole('button', { name: 'Save delegation' }).click();
  await expect(owner.getByText('Saved.')).toBeVisible();
  await owner.context().close();

  const helper = await loginAs(browser, IDS.helper);
  await helper.goto(`/dashboard/${GUILD}/welcome`);
  await expect(helper.getByRole('heading', { name: 'Welcome & goodbye' })).toBeVisible();
  // Navigation only shows what they may use.
  await expect(helper.getByRole('link', { name: 'Moderation & cases' })).toHaveCount(0);
  await helper.goto(`/dashboard/${GUILD}/moderation`);
  await expect(helper).toHaveURL(/denied=1/);
  const statuses = await helper.evaluate(async (g) => {
    const put = (url: string, body: unknown) => fetch(url, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }).then((r) => r.status);
    return {
      delegation: await put(`/api/guilds/${g}/delegations`, { delegations: [{ roleId: '444400000000000003', scopes: ['moderation'] }] }),
      moderation: await put(`/api/guilds/${g}/settings/moderation`, { value: {}, version: 0 }),
    };
  }, GUILD);
  expect(statuses).toEqual({ delegation: 403, moderation: 403 });
  await helper.context().close();
});

test('settings are validated server-side, including cross-server IDs', async ({ browser }) => {
  const page = await loginAs(browser, IDS.owner);
  await page.goto(`/dashboard/${GUILD}/welcome`);
  const message = page.getByLabel('Welcome message');
  await message.fill('Hello {user}, welcome to the kitchen!');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByText('Saved.')).toBeVisible();

  const result = await page.evaluate(async (g) => {
    const s = await (await fetch(`/api/guilds/${g}/settings`)).json();
    const res = await fetch(`/api/guilds/${g}/settings/logging`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ value: { ...s.settings.logging, modLogChannelId: '999999999999999999' }, version: s.version }),
    });
    return { status: res.status, body: await res.json() };
  }, GUILD);
  expect(result.status).toBe(400);
  expect(result.body.error).toMatch(/not in this server/);
  await page.context().close();
});
