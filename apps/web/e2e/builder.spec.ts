import { expect, test, type Browser, type Page } from '@playwright/test';
import { IDS } from './fake-discord';

const DISCORD = 'http://127.0.0.1:4010';
const GUILD = IDS.guild;

async function loginAs(browser: Browser, userId: string): Promise<Page> {
  await fetch(`${DISCORD}/_test/login-as`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ userId }) });
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.goto('/login');
  await page.getByRole('link', { name: 'Continue with Discord' }).click();
  await page.waitForURL('**/dashboard');
  return page;
}

async function discordState() {
  return (await fetch(`${DISCORD}/_test/state`)).json() as Promise<{ roles: Array<{ name: string; permissions: string }>; channels: Array<{ name: string; type: number; parent_id: string | null; permission_overwrites: unknown[] }>; messages: unknown[]; commands: Array<{ name: string }> }>;
}

test.describe.configure({ mode: 'serial' });

test('owner signs in, applies a template through preview + confirmation, and the worker builds it', async ({ browser }) => {
  const page = await loginAs(browser, IDS.owner);
  await expect(page.getByRole('heading', { name: 'Choose a server' })).toBeVisible();
  await page.getByRole('link', { name: /Fake Kitchen/ }).click();
  await expect(page.getByRole('heading', { name: 'Fake Kitchen' })).toBeVisible();

  await page.getByRole('link', { name: 'AI server builder' }).first().click();
  await page.getByRole('button', { name: /Cooking community/ }).click();
  await expect(page.getByText('Plan v1')).toBeVisible();

  // Preview: counts, diff and the elevation acknowledgement gate.
  await expect(page.getByText(/\+\d+ create/)).toBeVisible();
  const apply = page.getByRole('button', { name: /^Apply \d+ change/ });
  await expect(apply).toBeDisabled();
  await page.getByText('I understand this grants the powerful permissions').click();
  await expect(apply).toBeEnabled();
  await apply.click();

  await expect(page.getByText('Applying plan')).toBeVisible();
  await expect(page.getByText(/\d+ done · 0 failed/)).toBeVisible({ timeout: 90_000 });

  const state = await discordState();
  const names = state.channels.map((c) => c.name);
  expect(names).toEqual(expect.arrayContaining(['recipes', 'food-photos', 'mod-log', 'The Kitchen', 'Staff']));
  expect(state.roles.map((r) => r.name)).toEqual(expect.arrayContaining(['Moderator', 'Head Chef', 'Baker']));
  // Staff category is private: @everyone denied ViewChannel.
  const staff = state.channels.find((c) => c.name === 'Staff')!;
  expect(JSON.stringify(staff.permission_overwrites)).toContain(GUILD);
  // Additive: the pre-existing #general is untouched and not duplicated.
  expect(names.filter((n) => n === 'general')).toHaveLength(1);
  // Rules message + self-role panel were posted.
  expect(state.messages.length).toBeGreaterThanOrEqual(2);
  await page.context().close();
});

